#!/usr/bin/env python3
"""Regenerate the chart README's values reference from values.schema.json + values.yaml.

  python platform/charts/microservice/ci/gen_readme.py           # rewrite README.md
  python platform/charts/microservice/ci/gen_readme.py --check   # fail if out of date (tests/CI)

The schema is the contract; the README must never drift from it.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

CHART = Path(__file__).resolve().parents[1]
README = CHART / "README.md"
BEGIN, END = "<!-- values-reference:begin -->", "<!-- values-reference:end -->"


def main() -> int:
    schema = json.loads((CHART / "values.schema.json").read_text())
    defaults = yaml.safe_load((CHART / "values.yaml").read_text())
    defs = schema["definitions"]

    def resolve(p: dict) -> dict:
        while "$ref" in p:
            p = defs[p["$ref"].split("/")[-1]]
        return p

    def typ(p: dict) -> str:
        p = resolve(p)
        if "enum" in p:
            return " \\| ".join(f"`{e}`" for e in p["enum"])
        if "oneOf" in p:
            return " \\| ".join(typ(x) for x in p["oneOf"])
        t = p.get("type", "object")
        return "/".join(t) if isinstance(t, list) else t

    def default(path: list[str]) -> str:
        d = defaults
        for k in path:
            if not isinstance(d, dict) or k not in d:
                return ""
            d = d[k]
        if d in (None, "", {}, []):
            return ""
        return f"`{d}`" if isinstance(d, str) else f"`{json.dumps(d)}`"

    rows: list[str] = []

    def walk(props: dict, path: list[str], required: list[str]) -> None:
        for key, raw in props.items():
            p, full = resolve(raw), [*path, key]
            if key == "aws" and not path:
                continue
            if p.get("type") == "object" and "properties" in p and len(full) < 3 and key != "probes":
                walk(p["properties"], full, p.get("required", []))
                continue
            text = (raw.get("description") or p.get("description", "")).replace("|", "/")
            rows.append(
                f"| `{'.'.join(full)}` | {typ(raw)} | {'yes' if key in required else ''} | {default(full)} | {text} |"
            )

    walk(schema["properties"], [], schema["required"])
    aws = []
    for kind in ("sqs", "sns", "s3", "dynamodb", "rds"):
        item = defs[kind]
        fields = ", ".join(
            f"`{f}`{'*' if f in item['required'] else ''}: {typ(v)}" for f, v in item["properties"].items()
        )
        aws.append(f"| `aws.{kind}[]` | {fields} |")

    block = "\n".join(
        [
            BEGIN,
            "Generated by `ci/gen_readme.py` from the schema (`*` = required). `global.*` is pipeline-injected.",
            "",
            "| Key | Type | Required | Default | Description |",
            "|---|---|---|---|---|",
            *rows,
            "",
            "### AWS resources",
            "",
            "| Key | Fields (`*` required) |",
            "|---|---|",
            *aws,
            END,
        ]
    )
    current = README.read_text()
    updated = current[: current.index(BEGIN)] + block + current[current.index(END) + len(END) :]
    if "--check" in sys.argv:
        if updated != current:
            print("README.md values reference is stale: run ci/gen_readme.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(updated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
